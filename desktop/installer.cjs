'use strict';
// `ai-office install-app`가 쓰는 설치·삭제 로직.
//
// node_modules/electron이 이미 받아 둔 Electron.app을 ~/Applications/AI Office.app으로
// 복사해, 이름과 아이콘만 바꾸고 다시 서명한다. 저장소 코드는 복사하지 않고,
// Contents/Resources/app/index.js가 이 저장소의 desktop/main.cjs를 그대로 require한다.
//
// 02-설계.md(검토 반영 포함)를 그대로 구현한다. 자세한 단계 설명은 그 문서를 본다.
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { markPng } = require('./icon.cjs');

const APP_NAME = 'AI Office';
const BUNDLE_ID = 'com.ai-office.desktop';

function destDir() {
  return path.join(os.homedir(), 'Applications');
}

function destApp() {
  return path.join(destDir(), `${APP_NAME}.app`);
}

/** desktop/installer.cjs 기준 저장소 루트. */
function repoRoot() {
  return path.resolve(__dirname, '..');
}

// ------------------------------------------------------------ 순수 함수

/**
 * 템플릿 Electron.app 경로를 계산하고 검증한다. electronBinPath는
 * `.../Electron.app/Contents/MacOS/Electron` 형태여야 한다.
 */
function resolveTemplateApp(electronBinPath) {
  const macosDir = path.dirname(electronBinPath); // .../Electron.app/Contents/MacOS
  const contentsDir = path.dirname(macosDir); // .../Electron.app/Contents
  const appDir = path.dirname(contentsDir); // .../Electron.app
  if (path.basename(appDir) !== 'Electron.app') {
    return { ok: false, error: `electron 패키지 구조가 예상과 달라요(${electronBinPath}). electron 버전을 확인해 주세요.` };
  }
  return { ok: true, path: appDir };
}

/** macOS .iconset 규칙에 맞는 {name, size, template} 목록. */
function iconsetFiles() {
  return [
    { name: 'icon_16x16.png', size: 16, template: false },
    { name: 'icon_16x16@2x.png', size: 32, template: false },
    { name: 'icon_32x32.png', size: 32, template: false },
    { name: 'icon_32x32@2x.png', size: 64, template: false },
    { name: 'icon_128x128.png', size: 128, template: false },
    { name: 'icon_128x128@2x.png', size: 256, template: false },
    { name: 'icon_256x256.png', size: 256, template: false },
    { name: 'icon_256x256@2x.png', size: 512, template: false },
    { name: 'icon_512x512.png', size: 512, template: false },
    { name: 'icon_512x512@2x.png', size: 1024, template: false },
  ];
}

/**
 * `Contents/Resources/app/index.js`에 쓸 소스 코드 문자열. repoRootPath를
 * JSON.stringify로 문자열 리터럴에 안전하게 넣는다(공백·따옴표가 있어도 깨지지 않는다).
 */
function buildAppStubSource(repoRootPath) {
  const mainPath = path.join(repoRootPath, 'desktop', 'main.cjs');
  return [
    "// Generated by `ai-office install-app` (or `npm run install-app`). Do not edit by hand.",
    '// Loads this repository\'s desktop app in place of the default Electron "Get Started"',
    '// screen. Moving or deleting the repository breaks this app; reinstall after moving it.',
    `require(${JSON.stringify(mainPath)});`,
    '',
  ].join('\n');
}

/** 기존 destApp()의 CFBundleIdentifier가 우리 것인지. */
function isOurApp(identifier) {
  return identifier === BUNDLE_ID;
}

/** Info.plist에 적용할 {key, type, value} 목록. */
function plistEdits({ version } = {}) {
  return [
    { key: 'CFBundleName', type: 'string', value: APP_NAME },
    { key: 'CFBundleDisplayName', type: 'string', value: APP_NAME },
    { key: 'CFBundleIdentifier', type: 'string', value: BUNDLE_ID },
    { key: 'CFBundleExecutable', type: 'string', value: APP_NAME },
    { key: 'CFBundleIconFile', type: 'string', value: 'icon' },
    { key: 'CFBundleShortVersionString', type: 'string', value: version },
    { key: 'CFBundleVersion', type: 'string', value: version },
  ];
}

// ------------------------------------------------------------ 실제 설치·삭제

function failed(result) {
  return !result || result.error || result.status !== 0;
}

const NOT_DARWIN_ERROR = '이 설치는 macOS에서만 됩니다. 다른 OS에서는 `ai-office`로 브라우저 창을 쓰세요.';
const ELECTRON_MISSING_ERROR = 'electron이 설치되어 있지 않습니다. `npm ci` 이후 다시 시도하세요.';

function plistIdentifierOf(appPath, run, fsImpl) {
  if (!fsImpl.existsSync(appPath)) return { present: false };
  const result = run('/usr/libexec/PlistBuddy', ['-c', 'Print :CFBundleIdentifier', path.join(appPath, 'Contents', 'Info.plist')], { encoding: 'utf8' });
  if (failed(result)) return { present: true, identifier: null };
  return { present: true, identifier: String(result.stdout || '').trim() };
}

/**
 * `~/Applications/AI Office.app`을 만들거나 새로 고쳐 만든다.
 *
 * `electronBin`은 테스트 전용 주입 지점이다(실제 호출은 항상 `require('electron')`을 쓴다).
 * `run`/`fs`는 외부 명령 실행과 파일시스템 호출을 주입받는다(기본값은 진짜 spawnSync/node:fs).
 */
function installApp({ run = spawnSync, fs: fsImpl = fs, electronBin: electronBinOverride } = {}) {
  if (process.platform !== 'darwin') return { ok: false, error: NOT_DARWIN_ERROR };

  let electronBin = electronBinOverride;
  if (electronBin === undefined) {
    try {
      // eslint-disable-next-line global-require
      electronBin = require('electron');
    } catch {
      return { ok: false, error: ELECTRON_MISSING_ERROR };
    }
  }
  if (typeof electronBin !== 'string' || !fsImpl.existsSync(electronBin)) return { ok: false, error: ELECTRON_MISSING_ERROR };

  const template = resolveTemplateApp(electronBin);
  if (!template.ok) return template;

  const existing = destApp();
  const existingInfo = plistIdentifierOf(existing, run, fsImpl);
  if (existingInfo.present && !isOurApp(existingInfo.identifier)) {
    return {
      ok: false,
      error: '~/Applications/AI Office.app 위치에 이미 다른 앱이 있어서 설치를 멈췄습니다. 그 앱을 다른 이름으로 옮긴 뒤 다시 실행해 주세요.',
    };
  }

  let tmpRoot = null;
  let movedOut = false;
  try {
    tmpRoot = fsImpl.mkdtempSync(path.join(os.tmpdir(), 'ai-office-install-'));
    const tmpApp = path.join(tmpRoot, `${APP_NAME}.app`);

    const ditto = run('ditto', [template.path, tmpApp]);
    if (failed(ditto)) return { ok: false, error: `템플릿 앱을 복사하지 못했습니다(ditto 종료 코드 ${ditto && ditto.status}).` };

    fsImpl.renameSync(path.join(tmpApp, 'Contents', 'MacOS', 'Electron'), path.join(tmpApp, 'Contents', 'MacOS', APP_NAME));

    let pkg;
    try {
      pkg = JSON.parse(fsImpl.readFileSync(path.join(repoRoot(), 'package.json'), 'utf8'));
    } catch (err) {
      return { ok: false, error: `저장소의 package.json을 읽지 못했습니다: ${err && err.message ? err.message : err}` };
    }

    const plistPath = path.join(tmpApp, 'Contents', 'Info.plist');
    for (const edit of plistEdits({ version: pkg.version })) {
      if (String(edit.value).includes('"')) {
        return { ok: false, error: `Info.plist 값에 큰따옴표가 있어서 안전하게 적용할 수 없습니다(${edit.key}).` };
      }
      run('/usr/libexec/PlistBuddy', ['-c', `Delete :${edit.key}`, plistPath]); // 키가 원래 없을 수 있어 실패를 무시한다
      const add = run('/usr/libexec/PlistBuddy', ['-c', `Add :${edit.key} ${edit.type} "${edit.value}"`, plistPath]);
      if (failed(add)) return { ok: false, error: `Info.plist의 ${edit.key} 값을 설정하지 못했습니다.` };
    }

    const resourcesDir = path.join(tmpApp, 'Contents', 'Resources');
    fsImpl.rmSync(path.join(resourcesDir, 'electron.icns'), { force: true });

    const iconsetDir = path.join(tmpRoot, 'icon.iconset');
    fsImpl.mkdirSync(iconsetDir, { recursive: true });
    for (const file of iconsetFiles()) {
      fsImpl.writeFileSync(path.join(iconsetDir, file.name), markPng(file.size, { background: true }));
    }
    const iconutil = run('iconutil', ['-c', 'icns', iconsetDir, '-o', path.join(resourcesDir, 'icon.icns')]);
    if (failed(iconutil)) return { ok: false, error: `앱 아이콘을 만들지 못했습니다(iconutil 종료 코드 ${iconutil && iconutil.status}).` };

    const appDir = path.join(resourcesDir, 'app');
    fsImpl.mkdirSync(appDir, { recursive: true });
    fsImpl.writeFileSync(path.join(appDir, 'package.json'), `${JSON.stringify({ name: 'ai-office-desktop-app', version: pkg.version, main: 'index.js' }, null, 2)}\n`);
    fsImpl.writeFileSync(path.join(appDir, 'index.js'), buildAppStubSource(repoRoot()));

    // --deep 없이 먼저 서명하고, 검증에 실패할 때만 --deep으로 다시 서명한다(설계 검토 반영 3번).
    let codesign = run('codesign', ['--force', '--sign', '-', tmpApp]);
    if (failed(codesign)) return { ok: false, error: `앱 서명에 실패했습니다(codesign 종료 코드 ${codesign && codesign.status}).` };
    const verify = run('codesign', ['--verify', '--deep', '--strict', tmpApp]);
    if (failed(verify)) {
      codesign = run('codesign', ['--force', '--deep', '--sign', '-', tmpApp]);
      if (failed(codesign)) return { ok: false, error: `앱 서명에 실패했습니다(codesign --deep 종료 코드 ${codesign && codesign.status}).` };
    }

    run('xattr', ['-cr', tmpApp]); // 격리 속성 제거는 실패해도 무시해도 되는 보조 단계

    fsImpl.mkdirSync(destDir(), { recursive: true });
    if (existingInfo.present) fsImpl.rmSync(existing, { recursive: true, force: true });
    try {
      fsImpl.renameSync(tmpApp, existing);
    } catch (err) {
      if (err && err.code === 'EXDEV') {
        const moved = run('ditto', [tmpApp, existing]);
        if (failed(moved)) return { ok: false, error: `앱을 ~/Applications로 옮기지 못했습니다(ditto 종료 코드 ${moved && moved.status}).` };
        fsImpl.rmSync(tmpApp, { recursive: true, force: true });
      } else {
        throw err;
      }
    }
    movedOut = true;
    return { ok: true, path: existing };
  } catch (err) {
    return { ok: false, error: err && err.message ? err.message : String(err) };
  } finally {
    if (tmpRoot && !movedOut) {
      try {
        fsImpl.rmSync(tmpRoot, { recursive: true, force: true });
      } catch {
        /* 정리 실패는 무시한다 */
      }
    }
  }
}

/** 설치한 `~/Applications/AI Office.app`을 지운다(우리가 만든 앱일 때만). */
function uninstallApp({ run = spawnSync, fs: fsImpl = fs } = {}) {
  const existing = destApp();
  const existingInfo = plistIdentifierOf(existing, run, fsImpl);
  if (!existingInfo.present) return { ok: true, removed: false };
  if (!isOurApp(existingInfo.identifier)) {
    return { ok: false, error: `${existing}은 우리가 만든 앱이 아니라서 지우지 않았습니다.` };
  }
  fsImpl.rmSync(existing, { recursive: true, force: true });
  return { ok: true, removed: true };
}

module.exports = {
  APP_NAME,
  BUNDLE_ID,
  destDir,
  destApp,
  resolveTemplateApp,
  iconsetFiles,
  buildAppStubSource,
  isOurApp,
  plistEdits,
  installApp,
  uninstallApp,
};
